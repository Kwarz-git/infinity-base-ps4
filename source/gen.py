#!/usr/bin/env python3
"""Generates lib.h (figure library) and web.h (phone web page) from InfinityPi's bins/ folder and index.html.
Usage: python3 gen.py /path/to/infinity-pi/bins
"""
import os, sys

bins = sys.argv[1]
here = os.path.dirname(os.path.abspath(__file__))
CATS = ["Characters", "Playsets", "PowerDiscs", "ToyBoxes"]
VERS = ["1.0", "2.0", "3.0"]

entries = []
for vi, v in enumerate(VERS):
    for ci, c in enumerate(CATS):
        d = os.path.join(bins, v, c)
        if not os.path.isdir(d):
            continue
        for f in sorted(os.listdir(d)):
            if not f.endswith(".bin"):
                continue
            data = open(os.path.join(d, f), "rb").read()
            if len(data) != 320:
                continue
            entries.append((f[:-4], ci, vi, data))

names = b""
offs = []
for n, _, _, _ in entries:
    offs.append(len(names))
    names += n.encode("utf-8") + b"\0"

with open(os.path.join(here, "lib.h"), "w") as o:
    o.write("/* generated by gen.py - do not edit */\n")
    o.write("#define LIB_N %d\n" % len(entries))
    o.write("static const uint8_t LIB_CAT[LIB_N] = {%s};\n" % ",".join(str(e[1]) for e in entries))
    o.write("static const uint8_t LIB_VER[LIB_N] = {%s};\n" % ",".join(str(e[2]) for e in entries))
    o.write("static const uint16_t LIB_OFF[LIB_N] = {%s};\n" % ",".join(str(x) for x in offs))
    o.write("static const unsigned char LIB_NAMES[%d] = {%s};\n" % (len(names), ",".join(str(b) for b in names)))
    o.write("static const uint8_t LIB_DATA[LIB_N][320] = {\n")
    for e in entries:
        o.write("{" + ",".join(str(b) for b in e[3]) + "},\n")
    o.write("};\n")

html = open(os.path.join(here, "index.html"), "rb").read()
with open(os.path.join(here, "web.h"), "w") as o:
    o.write("/* generated by gen.py - do not edit */\n")
    o.write("static const unsigned char WEB_PAGE[%d] = {%s};\n" % (len(html), ",".join(str(b) for b in html)))

print("figures:", len(entries), "names blob:", len(names), "html:", len(html))

/* a real base sends this by itself when a figure leaves the pad: AB 04 <slot id> 09 01 <checksum> */
static void notify_removed(int s)
{
    Resp r;
    memset(&r, 0, sizeof(r));
    r.d[0] = 0xAB; r.d[1] = 0x04; r.d[2] = (uint8_t)(sid_of(s) + s); r.d[3] = 0x09; r.d[4] = 0x01;
    r.d[5] = checksum(r.d, 5);
    lock();
    if (g_game_seen && g_nresp < 16)
        g_resp[g_nresp++] = r;
    unlock();
}

/* libusb-ABI config descriptor tree: 1 HID interface, EP 0x81 IN + EP 0x01 OUT (32 bytes). Struct sizes
 * as the game expects them (endpoint descriptors are 0x20 bytes apart). */
static void init_fake(void)
{
    uint8_t *m = g_fake_mem;
    static const uint8_t hid[9] = {0x09, 0x21, 0x11, 0x01, 0x00, 0x01, 0x22, 0x1d, 0x00};
    memset(m, 0, sizeof(g_fake_mem));
    m[512] = 9; m[513] = 2; m[514] = 41; m[516] = 1; m[517] = 1; m[519] = 0x80; m[520] = 0x96;
    *(uint64_t *)(m + 512 + 16) = (uint64_t)(m + 576);   /* interface[] */
    *(uint64_t *)(m + 576) = (uint64_t)(m + 592);        /* altsetting */
    *(int32_t *)(m + 576 + 8) = 1;
    m[592] = 9; m[593] = 4; m[596] = 2; m[597] = 3;      /* interface 0, 2 endpoints, HID */
    *(uint64_t *)(m + 592 + 16) = (uint64_t)(m + 640);   /* endpoint[] */
    *(uint64_t *)(m + 592 + 24) = (uint64_t)(m + 704);   /* extra = HID descriptor */
    *(int32_t *)(m + 592 + 32) = 9;
    m[640] = 7; m[641] = 5; m[642] = 0x81; m[643] = 3; m[644] = 0x20; m[646] = 1;
    m[672] = 7; m[673] = 5; m[674] = 0x01; m[675] = 3; m[676] = 0x20; m[678] = 1;
    memcpy(m + 704, hid, 9);
}

static int in_fake(uint64_t p) { return p >= (uint64_t)g_fake_mem && p < (uint64_t)g_fake_mem + sizeof(g_fake_mem); }

static int tracked(uint64_t t)
{
    int i, r = 0;
    if (!t) return 0;
    lock();
    for (i = 0; i < NTRK; i++)
        if (g_trk[i] == t) r = 1;
    unlock();
    return r;
}

static uint64_t handle_submit(uint64_t t)
{
    uint8_t ep = *(uint8_t *)(t + 9);
    int len = *(int32_t *)(t + 20);
    uint64_t buf = *(uint64_t *)(t + 48);
    uint8_t tmp[32];
    memset(tmp, 0, sizeof(tmp));
    if (!(ep & 0x80) && buf > 0x10000 && len > 0)
        memcpy(tmp, (const void *)buf, len > 32 ? 32 : len);
    lock();
    g_trk[g_ntrk++ % NTRK] = t;
    if (ep & 0x80) {
        if (g_ninq < 8)
            g_inq[g_ninq++] = t;
    } else if (g_noq < 16) {
        OutEnt *e = &g_oq[g_noq++];
        e->t = t;
        e->len = len > 32 ? 32 : (len < 0 ? 0 : len);
        memcpy(e->d, tmp, 32);
    }
    unlock();
    return 0;
}

static uint64_t generic_call(int idx, uint64_t a, uint64_t b, uint64_t c, uint64_t d, uint64_t e,
                             uint64_t f, uint64_t g, uint64_t h)
{
    Slot *s = &g_slot[idx];
    s->cnt++;
    switch (s->role) {
    case R_LIST: {
        uint64_t r = ((raw8_fn)s->orig)(a, b, c, d, e, f, g, h);
        int cnt = (int)r;
        if (cnt >= 0 && cnt <= 12 && is_ptr(a)) {
            uint64_t real = *(uint64_t *)a;
            int i;
            if (is_ptr(real))
                for (i = 0; i < cnt; i++)
                    g_fake_list[i] = ((uint64_t *)real)[i];
            g_fake_list[cnt] = FAKE_DEV;
            g_fake_list[cnt + 1] = 0;
            g_real_list = real;
            *(uint64_t *)a = (uint64_t)g_fake_list;
            return (uint64_t)(uint32_t)(cnt + 1);
        }
        return r;
    }
    case R_FREE:
        if (a == (uint64_t)g_fake_list) {
            uint64_t r = ((raw8_fn)s->orig)(g_real_list, 0, c, d, e, f, g, h);
            g_real_list = 0;
            return r;
        }
        break;
    case R_DESC:
        if (a == FAKE_DEV && b > 0x10000) {
            static const uint8_t desc[18] = {18, 1, 0x00, 0x02, 0, 0, 0, 32, 0x6f, 0x0e, 0x29, 0x01,
                                             0x00, 0x02, 1, 2, 0, 1};
            memcpy((void *)b, desc, 18);
            return 0;
        }
        break;
    case R_OPEN:
        if (a == FAKE_DEV) {
            if (b > 0x10000)
                *(uint64_t *)b = FAKE_HANDLE;
            return 0;
        }
        break;
    case R_SUBMIT:
        if (is_ptr(a) && *(uint64_t *)a == FAKE_HANDLE)
            return handle_submit(a);
        break;
    case R_REF:
        if (a == FAKE_DEV)
            return a;
        break;
    case R_GETCFG:
        if (a == FAKE_HANDLE) {
            if (b > 0x10000)
                *(int32_t *)b = 1;
            return 0;
        }
        break;
    case R_ACFG:
        if (a == FAKE_DEV) {
            if (b > 0x10000)
                *(uint64_t *)b = FAKE_CFG;
            return 0;
        }
        break;
    case R_ALLOC:
    case R_FILL:
        break;
    default:
        if (a == FAKE_DEV || a == FAKE_HANDLE || b == FAKE_DEV || b == FAKE_HANDLE || in_fake(a) ||
            in_fake(b) || tracked(a) || tracked(b)) {
            if (s->cnt > 3)
                sceKernelUsleep(1000); /* calls that poll in a loop: do not spin */
            return 0;
        }
        break;
    }
    return ((raw8_fn)s->orig)(a, b, c, d, e, f, g, h);
}


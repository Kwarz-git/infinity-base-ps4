/*
 * infinity_base - GoldHEN plugin: virtual Disney Infinity Base for the PS4.
 *
 * Emulates the USB base (VID 0E6F / PID 0129) that the game looks for, by sitting between the game and
 * libSceUsbd. The base protocol is a port of InfinityPi (itself a port of RPCS3). Figures are chosen from
 * a phone/PC browser: http://<ps4-ip>:8080
 *
 * How it works
 *  1. The game keeps ~19 pointers to libSceUsbd functions in its read-only data. We swap them for our own
 *     functions (making the page writable for a moment). No code is ever patched.
 *  2. GetDeviceList gets one extra, fake device. Everything the game then does with that device is
 *     answered here; real USB devices are untouched.
 *  3. Transfers submitted to the fake device are handled by the protocol engine and completed by calling
 *     the game's own callback from a worker thread.
 *
 * Files in /data/GoldHEN/infinity/  : state.txt (chosen figures), saves/ (figure progress).
 */

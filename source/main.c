/* completes a fake transfer: status OK, actual_length set, then the game's own callback */
static void finish_transfer(uint64_t t, int actual)
{
    uint64_t cb = *(uint64_t *)(t + 32);
    *(int32_t *)(t + 16) = 0;
    *(int32_t *)(t + 24) = actual;
    if (cb >= g_text_lo && cb < g_text_hi)
        ((cb_fn)cb)(t);
}


/* worker: runs the protocol for packets the game sent, delivers replies, saves progress */
static void *worker_thread(void *arg)
{
    (void)arg;
    for (;;) {
        OutEnt e;
        int have_out = 0, have_in = 0, s;
        uint64_t tin = 0;
        Resp r;
        sceKernelUsleep(2000);
        g_tick++;
        for (s = 0; s < 9; s++)
            if (g_dirty[s] && g_tick - g_dirty_tick[s] > 500) /* ~1 s after the last change */
                flush_slot(s);
        lock();
        if (g_noq > 0) {
            e = g_oq[0];
            memmove(g_oq, g_oq + 1, sizeof(OutEnt) * (g_noq - 1));
            g_noq--;
            have_out = 1;
        }
        unlock();
        if (have_out) {
            finish_transfer(e.t, e.len);
            if (e.len >= 4 && e.d[0] == 0xFF) {
                Resp rr;
                lock();
                process_packet(e.d, rr.d);
                if (g_nresp < 16)
                    g_resp[g_nresp++] = rr;
                unlock();
                if (!g_game_seen) {
                    g_game_seen = 1;
                }
            }
        }
        lock();
        if (g_nresp > 0 && g_ninq > 0) {
            r = g_resp[0];
            memmove(g_resp, g_resp + 1, sizeof(Resp) * (g_nresp - 1));
            g_nresp--;
            tin = g_inq[0];
            memmove(g_inq, g_inq + 1, sizeof(uint64_t) * (g_ninq - 1));
            g_ninq--;
            have_in = 1;
        }
        unlock();
        if (have_in) {
            uint64_t buf = *(uint64_t *)(tin + 48);
            int len = *(int32_t *)(tin + 20);
            int n = len < 32 ? len : 32;
            if (buf > 0x10000 && n > 0)
                memcpy((void *)buf, r.d, n);
            finish_transfer(tin, n);
        }
    }
    return NULL;
}

/* ------------------------------------------------------------------ pointer swapping */

static void install_swaps(void)
{
    OrbisKernelModuleInfo info;
    uint32_t sg;
    int i;

    memset(&info, 0, sizeof(info));
    info.size = sizeof(info);
    if (sceKernelGetModuleInfo(0, &info) != 0)
        return;
    for (sg = 0; sg < info.segmentCount && sg < 4; sg++)
        if (info.segmentInfo[sg].prot & 4) {
            g_text_lo = (uint64_t)info.segmentInfo[sg].address;
            g_text_hi = g_text_lo + info.segmentInfo[sg].size;
        }
    for (sg = 0; sg < info.segmentCount && sg < 4; sg++) {
        OrbisKernelVirtualQueryInfo vq;
        uint64_t base = (uint64_t)info.segmentInfo[sg].address;
        uint64_t limit = base + info.segmentInfo[sg].size, j;
        volatile uint64_t *p = (volatile uint64_t *)base;
        memset(&vq, 0, sizeof(vq));
        if (sceKernelVirtualQuery((const void *)base, 0, &vq, sizeof(vq)) != 0)
            continue;
        if (!(vq.prot & 1) || (vq.prot & 4))
            continue; /* readable, non-executable only */
        if ((uint64_t)vq.end_addr > limit)
            limit = (uint64_t)vq.end_addr < limit + 0x4000000ULL ? (uint64_t)vq.end_addr : limit + 0x4000000ULL;
        for (j = 0; j < (limit - base) / 8; j++) {
            uint64_t v = p[j];
            if (v >= g_usbd_lo && v < g_usbd_hi && g_nslot < MAXSLOT) {
                Slot *s = &g_slot[g_nslot];
                int k;
                s->orig = v;
                s->slot_addr = base + j * 8;
                s->role = R_OTHER;
                /* roles identified from the game's behaviour (see notes): +0x410 FreeDeviceList,
                 * +0x430 RefDevice, +0x520 GetConfiguration, +0x6c0 GetActiveConfigDescriptor */
                if (v - g_usbd_lo == 0x410) s->role = R_FREE;
                if (v - g_usbd_lo == 0x430) s->role = R_REF;
                if (v - g_usbd_lo == 0x520) s->role = R_GETCFG;
                if (v - g_usbd_lo == 0x6c0) s->role = R_ACFG;
                for (k = 0; k < NFN; k++)
                    if (g_real[k] == v) {
                        if (k == 1) s->role = R_LIST;
                        if (k == 2) s->role = R_DESC;
                        if (k == 3) s->role = R_OPEN;
                        if (k == 9) s->role = R_ALLOC;
                        if (k == 10) s->role = R_FILL;
                        if (k == 12) s->role = R_SUBMIT;
                    }
                g_nslot++;
            }
        }
    }
    if (!g_nslot)
        return;
    for (i = 0; i < g_nslot; i++) {
        Slot *s = &g_slot[i];
        uint64_t page = s->slot_addr & ~0xFFFULL;
        OrbisKernelVirtualQueryInfo vq;
        int writable, r1 = 0;
        memset(&vq, 0, sizeof(vq));
        sceKernelVirtualQuery((const void *)s->slot_addr, 0, &vq, sizeof(vq));
        writable = (vq.prot & 2) != 0;
        if (!writable)
            r1 = sceKernelMprotect((const void *)page, 0x1000, 3);
        if (r1 == 0)
            *(volatile uint64_t *)s->slot_addr = g_gw[i];
        if (!writable && r1 == 0)
            sceKernelMprotect((const void *)page, 0x1000, vq.prot & 7);
    }
    g_installed = 1;
}

static void check_for_usbd(void)
{
    OrbisKernelModule h[256];
    size_t n = 0, i;
    if (sceKernelGetModuleList(h, 256, &n) != 0)
        return;
    for (i = 0; i < n && i < 256; i++) {
        OrbisKernelModuleInfo info;
        uint32_t s;
        int k;
        memset(&info, 0, sizeof(info));
        info.size = sizeof(info);
        if (sceKernelGetModuleInfo(h[i], &info) != 0 || !contains_ci(info.name, "libsceusbd"))
            continue;
        for (s = 0; s < info.segmentCount && s < 4; s++) {
            uint64_t a = (uint64_t)info.segmentInfo[s].address;
            uint64_t b = a + info.segmentInfo[s].size;
            if (!g_usbd_lo || a < g_usbd_lo) g_usbd_lo = a;
            if (b > g_usbd_hi) g_usbd_hi = b;
        }
        for (k = 0; k < NFN; k++) {
            void *addr = NULL;
            sceKernelDlsym((int32_t)h[i], g_names[k], &addr);
            g_real[k] = (uint64_t)addr;
        }
        install_swaps();
        return;
    }
}

static void *watch_thread(void *arg)
{
    int tick;
    (void)arg;
    for (tick = 0; tick < 6000 && !g_installed; tick++) { /* up to 10 minutes */
        sceKernelUsleep(100000);
        check_for_usbd();
    }
    return NULL;
}

/* ------------------------------------------------------------------ web server (phone UI) */

static void http_send(int c, const void *p, size_t n)
{
    const char *q = (const char *)p;
    while (n) {
        int r = send(c, q, n, 0x20000); /* MSG_NOSIGNAL */
        if (r <= 0)
            return;
        q += r;
        n -= (size_t)r;
    }
}

static void http_head(int c, const char *type, int len)
{
    char h[200];
    int n;
    if (len >= 0)
        n = snprintf(h, sizeof(h), "HTTP/1.1 200 OK\r\nContent-Type: %s\r\nContent-Length: %d\r\nCache-Control: no-store\r\nConnection: close\r\n\r\n", type, len);
    else
        n = snprintf(h, sizeof(h), "HTTP/1.1 200 OK\r\nContent-Type: %s\r\nCache-Control: no-store\r\nConnection: close\r\n\r\n", type);
    http_send(c, h, n);
}

static void send_state(int c)
{
    char b[200];
    int n;
    int32_t id[9];
    lock();
    memcpy(id, g_figid, sizeof(id));
    unlock();
    n = snprintf(b, sizeof(b), "{\"s\":[%d,%d,%d,%d,%d,%d,%d,%d,%d],\"c\":%d}", (int)id[0], (int)id[1],
                 (int)id[2], (int)id[3], (int)id[4], (int)id[5], (int)id[6], (int)id[7], (int)id[8],
                 g_game_seen ? 1 : 0);
    http_head(c, "application/json", n);
    http_send(c, b, n);
}

static void send_lib(int c)
{
    char buf[2048];
    int len = 0, i;
    http_head(c, "application/json; charset=utf-8", -1);
    buf[len++] = '[';
    for (i = 0; i < LIB_N; i++) {
        const unsigned char *nm = &LIB_NAMES[LIB_OFF[i]];
        if (len > (int)sizeof(buf) - 400) {
            http_send(c, buf, len);
            len = 0;
        }
        if (i)
            buf[len++] = ',';
        buf[len++] = '[';
        buf[len++] = '"';
        while (*nm && len < (int)sizeof(buf) - 16) {
            if (*nm == '"' || *nm == '\\')
                buf[len++] = '\\';
            buf[len++] = (char)*nm++;
        }
        len += snprintf(buf + len, 16, "\",%d,%d]", LIB_CAT[i], LIB_VER[i]);
    }
    buf[len++] = ']';
    http_send(c, buf, len);
}

static int query_int(const char *q, const char *key, int def)
{
    size_t kl = strlen(key);
    while (*q) {
        if (strncmp(q, key, kl) == 0 && q[kl] == '=') {
            const char *p = q + kl + 1;
            int v = 0, any = 0, neg = 0;
            if (*p == '-') { neg = 1; p++; }
            while (*p >= '0' && *p <= '9') { v = v * 10 + (*p++ - '0'); any = 1; }
            return any ? (neg ? -v : v) : def;
        }
        while (*q && *q != '&') q++;
        if (*q == '&') q++;
    }
    return def;
}

static void http_serve(int c)
{
    char req[1024];
    char *path, *query, *end;
    int n = recv(c, req, sizeof(req) - 1, 0);
    if (n <= 0)
        return;
    req[n] = 0;
    if (strncmp(req, "GET ", 4) != 0)
        return;
    path = req + 4;
    end = path;
    while (*end && *end != ' ' && *end != '\r' && *end != '\n') end++;
    *end = 0;
    query = path;
    while (*query && *query != '?') query++;
    if (*query == '?')
        *query++ = 0;

    if (strcmp(path, "/") == 0 || strcmp(path, "/index.html") == 0) {
        http_head(c, "text/html; charset=utf-8", (int)sizeof(WEB_PAGE));
        http_send(c, WEB_PAGE, sizeof(WEB_PAGE));
    } else if (strcmp(path, "/api/state") == 0) {
        send_state(c);
    } else if (strcmp(path, "/api/lib") == 0) {
        send_lib(c);
    } else if (strcmp(path, "/api/place") == 0) {
        place_figure(query_int(query, "slot", -1), query_int(query, "id", -1));
        send_state(c);
    } else if (strcmp(path, "/api/remove") == 0) {
        remove_figure(query_int(query, "slot", -1));
        send_state(c);
    } else {
        static const char nf[] = "HTTP/1.1 404 Not Found\r\nContent-Length: 0\r\nConnection: close\r\n\r\n";
        http_send(c, nf, sizeof(nf) - 1);
    }
}

static void *web_thread(void *arg)
{
    struct { uint8_t len, fam; uint16_t port; uint32_t addr; uint8_t zero[8]; } sa;
    int s, one = 1;
    (void)arg;
    s = socket(2, 1, 0); /* AF_INET, SOCK_STREAM */
    if (s < 0)
        return NULL;
    setsockopt(s, 0xffff, 4, &one, sizeof(one)); /* SO_REUSEADDR */
    memset(&sa, 0, sizeof(sa));
    sa.len = 16;
    sa.fam = 2;
    sa.port = (uint16_t)((WEB_PORT >> 8) | ((WEB_PORT & 0xff) << 8));
    sa.addr = 0;
    if (bind(s, &sa, sizeof(sa)) != 0 || listen(s, 8) != 0) {
        close(s);
        return NULL;
    }
    for (;;) {
        struct { long sec; long usec; } tv = {3, 0};
        int c = accept(s, NULL, NULL);
        if (c < 0) {
            sceKernelUsleep(100000);
            continue;
        }
        setsockopt(c, 0xffff, 0x1006, &tv, sizeof(tv)); /* SO_RCVTIMEO */
        setsockopt(c, 0xffff, 0x800, &one, sizeof(one)); /* SO_NOSIGPIPE */
        http_serve(c);
        close(c);
    }
    return NULL;
}

